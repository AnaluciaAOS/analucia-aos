// ORD-0043 parts 1 and 5 (OBS-163, OBS-164): the handoff of an open run, on disk. `.analucia/views/handoff-<ID>.md`
// is generated and never committed: the run and its number, the minutes used and left, the last commit of the
// order, the files changed and not committed (from git, names only) and what comes next. The PreCompact hook writes
// it by itself with what it can know; `aos run handoff` writes it with the text of `--next`.
import { spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { readLog, timestampFor } from './log.mjs';

export const handoffRel = (id) => `.analucia/views/handoff-${id}.md`;

const git = (root, args) => {
  const r = spawnSync('git', ['-C', root, ...args], { encoding: 'utf8' });
  return r.status === 0 ? r.stdout.trimEnd() : null;
};

// The open run of an order, with the session that owns it now (ORD-0043 part 5: `aos run take` changes the owner).
export function openRunOf(events, id) {
  let open = null;
  for (const e of events) {
    if (e.subject !== id) continue;
    if (e.type === 'run.started') open = { event: e, session: typeof e.agent?.session === 'string' && e.agent.session ? e.agent.session : null };
    else if (e.type === 'run.finished') open = null;
    else if (open && e.type === 'operation.logged' && e.payload?.operation === 'run.take' && e.payload?.run === open.event.payload?.run) open.session = e.payload.session ?? null;
  }
  return open;
}

// What the handoff says, as data. Null when the order has no open run.
export function handoffOf(root, id, { next = null, now = new Date() } = {}) {
  const { events } = readLog(root);
  const open = openRunOf(events, id);
  if (!open) return null;
  const budget = open.event.payload?.budget ?? {};
  const used = Math.max(0, Math.round((now.getTime() - Date.parse(open.event.ts)) / 60000));
  const inGit = git(root, ['rev-parse', '--is-inside-work-tree']) === 'true';
  const last = inGit ? git(root, ['log', '-1', '--format=%h %s', `--grep=^Analucia-Order: ${id}$`]) : null;
  const dirty = inGit ? (git(root, ['status', '--porcelain']) ?? '').split('\n').filter(Boolean).map((l) => l.slice(3)) : null;
  return {
    id, run: open.event.payload?.run ?? null, attempts: budget.max_attempts ?? null, session: open.session, started: open.event.ts,
    minutes_used: used, minutes_left: Number.isFinite(budget.max_minutes) ? Math.max(0, budget.max_minutes - used) : null,
    branch: inGit ? git(root, ['rev-parse', '--abbrev-ref', 'HEAD']) : null, last_commit: last || null, uncommitted: dirty, next, written: timestampFor(root, now),
  };
}

export function handoffText(h, { by = 'aos run handoff' } = {}) {
  const lines = [
    `# Handoff of ${h.id}`,
    '',
    `Generated by ${by} at ${h.written}. Never committed. A new session reads this, takes the run with "aos run take ${h.id}" and goes on; it does not start another run.`,
    '',
    `- Run: run ${h.run ?? '?'} of ${h.attempts ?? '?'}, open since ${h.started}${h.session ? `, owned by the session ${h.session}` : ', with no recorded session'}`,
    `- Minutes: ${h.minutes_used} used, ${h.minutes_left ?? 'unknown'} left`,
    `- Branch: ${h.branch ?? 'not a git repository'}`,
    `- Last commit of the order: ${h.last_commit ?? 'none yet'}`,
    `- Changed and not committed: ${h.uncommitted === null ? 'not a git repository' : h.uncommitted.length ? `${h.uncommitted.length} file(s)` : 'nothing'}`,
    ...(h.uncommitted ?? []).map((f) => `  - ${f}`),
    `- Next: ${h.next ?? 'not stated (the handoff was written by a hook; read the report and the last commit of the order)'}`,
    '',
  ];
  return lines.join('\n');
}

// Writes the handoff and returns its path relative to the root, or null when the order has no open run.
export function writeHandoff(root, id, { next = null, by, now = new Date() } = {}) {
  const h = handoffOf(root, id, { next, now });
  if (!h) return null;
  const dir = join(root, '.analucia', 'views');
  mkdirSync(dir, { recursive: true });
  // A handoff written by a hook never replaces the "next" a session wrote for the same run.
  if (next === null && existsSync(join(root, handoffRel(id)))) {
    const kept = new RegExp(`^- Run: run ${h.run ?? '\\?'} of `, 'm').test(readFileSync(join(root, handoffRel(id)), 'utf8')) && /^- Next: (?!not stated)(.*)$/m.exec(readFileSync(join(root, handoffRel(id)), 'utf8'));
    if (kept) h.next = kept[1];
  }
  writeFileSync(join(root, handoffRel(id)), handoffText(h, { by }));
  return handoffRel(id);
}

export function removeHandoff(root, id) {
  rmSync(join(root, handoffRel(id)), { force: true });
}
